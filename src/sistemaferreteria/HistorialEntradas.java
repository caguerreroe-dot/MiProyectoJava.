public static void guardarEntradas() {
    try {
        java.io.FileOutputStream archivo =
                new java.io.FileOutputStream("entradas.dat");

        java.io.ObjectOutputStream salida =
                new java.io.ObjectOutputStream(archivo);

        salida.writeObject(entradas);

        salida.close();
        archivo.close();

    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(null,
                "Error al guardar las entradas");
    }
}

public void leerEntradas() {
    try {
        java.io.FileInputStream archivo =
                new java.io.FileInputStream("entradas.dat");

        java.io.ObjectInputStream entrada =
                new java.io.ObjectInputStream(archivo);

        entradas = (java.util.ArrayList<Object[]>) entrada.readObject();

        entrada.close();
        archivo.close();

    } catch (java.io.IOException | ClassNotFoundException e) {
        // Si no existe el archivo, comienza vacío.
    }
}

public void cargarEntradas() {
    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

    modelo.setRowCount(0);

    for (Object[] entrada : entradas) {
        modelo.addRow(entrada);
    }
}
