    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       String codigo = jTextField1.getText();
String cantidadTexto = jTextField2.getText();

if (codigo.isEmpty() || cantidadTexto.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Complete todos los campos");
    return;
}

try {
    int cantidad = Integer.parseInt(cantidadTexto);
    boolean encontrado = false;

    for (Object[] producto : GestionProductos.productos) {

        if (producto[0].toString().equals(codigo)) {

            int stock = Integer.parseInt(producto[3].toString());
            double precio = Double.parseDouble(producto[2].toString());

            if (cantidad <= 0 || cantidad > stock) {
                JOptionPane.showMessageDialog(this, "Cantidad no disponible");
                return;
            }

            double subtotal = precio * cantidad;

            modelo.addRow(new Object[]{
                producto[0],
                producto[1],
                precio,
                cantidad,
                subtotal
            });

            total += subtotal;

            jLabel3.setText("Total: $" + total);

            encontrado = true;
            break;
        }
    }

    if (!encontrado) {
        JOptionPane.showMessageDialog(this, "Producto no encontrado");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Ingrese una cantidad válida");
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        if (modelo.getRowCount() == 0) {
            GestionProductos.instancia.cargarProductos();
    JOptionPane.showMessageDialog(this, "No hay productos en la venta");
    return;
}

for (int i = 0; i < modelo.getRowCount(); i++) {
    ventas.add(new Object[]{
    modelo.getValueAt(i, 0),
    modelo.getValueAt(i, 1),
    modelo.getValueAt(i, 2),
    modelo.getValueAt(i, 3),
    modelo.getValueAt(i, 4),
    java.time.LocalDate.now().toString()
});

    String codigo = modelo.getValueAt(i, 0).toString();
    int cantidad = Integer.parseInt(
        modelo.getValueAt(i, 3).toString()
    );

    for (Object[] producto : GestionProductos.productos) {

        if (producto[0].toString().equals(codigo)) {

            int stock = Integer.parseInt(producto[3].toString());

            producto[3] = String.valueOf(stock - cantidad);

            break;
        }
    }
}
GestionProductos.instancia.guardarProductos();
Ventas.guardarVentas();
JOptionPane.showMessageDialog(this, "Venta realizada correctamente");

modelo.setRowCount(0);
total = 0;
jLabel3.setText("Total: $0");
    }//GEN-LAST:event_jButton3ActionPerformed

