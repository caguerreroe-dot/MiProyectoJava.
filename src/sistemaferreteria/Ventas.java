 public static void guardarVentas() {

    try {
        java.io.FileOutputStream archivo =
                new java.io.FileOutputStream("ventas.dat");

        java.io.ObjectOutputStream salida =
                new java.io.ObjectOutputStream(archivo);

        salida.writeObject(ventas);

        salida.close();
        archivo.close();

    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(null,
                "Error al guardar las ventas");
    }
}
 public static void leerVentas() {

    try {
        java.io.FileInputStream archivo =
                new java.io.FileInputStream("ventas.dat");

        java.io.ObjectInputStream entrada =
                new java.io.ObjectInputStream(archivo);

        ventas = (java.util.ArrayList<Object[]>) entrada.readObject();

        entrada.close();
        archivo.close();

    } catch (java.io.IOException | ClassNotFoundException e) {
        // Si no existe el archivo, comienza vacío.
    }
}
