    public void calcularValorInventario() {
    double total = 0;

    for (Object[] producto : GestionProductos.productos) {
        double precio = Double.parseDouble(producto[2].toString());
        int cantidad = Integer.parseInt(producto[3].toString());

        total += precio * cantidad;
    }

    jLabel2.setText("Valor total del inventario: $" + total);
}
    public void contarBajoInventario() {
    int contador = 0;

    for (Object[] producto : GestionProductos.productos) {
        int cantidad = Integer.parseInt(producto[3].toString());

        if (cantidad <= 5) {
            contador++;
        }
    }

    jLabel1.setText("Productos con bajo inventario: " + contador);
}
public void cargarReportes() {

    javax.swing.table.DefaultTableModel modelo =
        (javax.swing.table.DefaultTableModel) jTable1.getModel();

    modelo.setRowCount(0);

    for (Object[] producto : GestionProductos.productos) {

        modelo.addRow(new Object[]{
            producto[0],
            producto[1],
            producto[2],
            producto[3]
        });
    }
}
