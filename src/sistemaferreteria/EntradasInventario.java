    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
String codigo = txtCodigo.getText();
String cantidadTexto = txtCantidadIngresa.getText();

if (codigo.isEmpty() || cantidadTexto.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Complete todos los campos");
    return;
}

try {
    int cantidadEntrada = Integer.parseInt(cantidadTexto);

    if (cantidadEntrada <= 0) {
        JOptionPane.showMessageDialog(this, "Ingrese una cantidad mayor que cero");
        return;
    }

    boolean encontrado = false;

    for (Object[] producto : GestionProductos.productos) {
        if (producto[0].toString().equals(codigo)) {
            int cantidadActual = Integer.parseInt(producto[3].toString());
            int nuevaCantidad = cantidadActual + cantidadEntrada;

            producto[3] = String.valueOf(nuevaCantidad);
            txtCantidadActual.setText(String.valueOf(nuevaCantidad));
            if (GestionProductos.instancia != null) {
    GestionProductos.instancia.guardarProductos();
}
if (GestionProductos.instancia != null) {

    DefaultTableModel modelo =
        (DefaultTableModel) GestionProductos.instancia.jTable2.getModel();

    for (int i = 0; i < modelo.getRowCount(); i++) {

        if (modelo.getValueAt(i, 0).toString().equals(codigo)) {

            modelo.setValueAt(nuevaCantidad, i, 3);
            break;
        }
    }
}
HistorialEntradas.entradas.add(new Object[]{
    codigo,
    producto[1],
    cantidadEntrada,
    java.time.LocalDate.now().toString()
});
HistorialEntradas.guardarEntradas();
            encontrado = true;
            JOptionPane.showMessageDialog(this, "Entrada registrada correctamente");
            txtCantidadIngresa.setText("");
            break;
        }
    }

    if (!encontrado) {
        JOptionPane.showMessageDialog(this, "Primero debe buscar un producto válido");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "La cantidad debe ser un número entero");
}        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

